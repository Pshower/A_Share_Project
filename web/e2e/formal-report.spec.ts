import { test, expect } from '@playwright/test'

test('completed formal experiment exposes all seeds, data link and paired evaluation', async ({ page }) => {
  const experiments = await (await page.request.get('/api/experiments')).json()
  const experiment = experiments.find((e: any) => e.recipe.name === 'PPO multiseed 20260926 H1')
  test.skip(!experiment, 'Formal experiment is not present in this workspace')
  const state = await (await page.request.get('/api/experiments/' + experiment.id)).json()
  test.skip(state.summaries.length !== 3, 'Formal runs have not completed')
  await page.goto('/#experiments?id=' + experiment.id)
  await expect(page.getByRole('heading', { name: '已完成种子 · 验证对照', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'research_multiseed_20260926', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/formal-experiment-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(400)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: 'test-results/formal-experiment-mobile.png', fullPage: true })
  const reports = await (await page.request.get('/api/reports')).json()
  const report = reports.find((r: any) => r.run === state.summaries[0].job_id && r.name === 'selected_comparison')
  await page.goto('/#backtest?report=' + report.id)
  await expect(page.getByRole('heading', { name: 'PPO 与基线的配对比较', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Sortino', exact: true })).toBeVisible()
})
